//! Runs every measurement and prints a report in markdown, so the output can
//! be pasted into the README it justifies without being retyped — and so a
//! reader can regenerate it and check.
//!
//!   cargo run --release -- [--records N] [--seed S] [--repeats R]

mod codecs;
mod data;
mod formats;

use std::io::Write as _;

fn arg(name: &str, default: usize) -> usize {
    let mut args = std::env::args().skip(1);
    while let Some(current) = args.next() {
        if current == name {
            return args.next().and_then(|value| value.parse().ok()).unwrap_or(default);
        }
    }
    default
}

fn main() {
    let records = arg("--records", 2_000_000);
    let seed = arg("--seed", 20_260_817) as u64;
    let repeats = arg("--repeats", 3);

    let mut out = std::io::stdout().lock();

    let samples = data::generate(records, seed);
    let fixed = data::to_fixed_bytes(&samples);
    let jsonl = data::to_jsonl(&samples);

    let _ = writeln!(out, "# Results\n");
    let _ = writeln!(
        out,
        "Generated by `make bench`. The reading of these numbers is in \\
         [README.md](README.md); this file is only the measurement.\n"
    );
    let _ = writeln!(
        out,
        "Generated data: **{records} records**, seed `{seed}`, {} MiB as fixed 32-byte records \
         and {} MiB as JSONL. Every number below is the **best of {repeats} runs**, not the mean.\n",
        fixed.len() / (1024 * 1024),
        jsonl.len() / (1024 * 1024),
    );
    let _ = writeln!(
        out,
        "Reproduce with `make bench`, or `cargo run --release -- --records {records} --seed {seed}`.\n"
    );

    // --- codecs -------------------------------------------------------------
    let _ = writeln!(out, "## Codecs, on the fixed-layout records\n");
    let _ = writeln!(
        out,
        "This is the choice the container makes on your behalf. The input is the raw record \
         bytes — what a frame holds before it is compressed.\n"
    );
    let _ = writeln!(out, "| codec | size | ratio | compress | decompress |");
    let _ = writeln!(out, "|---|---:|---:|---:|---:|");
    let measurements = codecs::run_all(&fixed, repeats);
    for m in &measurements {
        let _ = writeln!(
            out,
            "| `{}` | {:.1} MiB | {:.2}x | {:.0} MiB/s | {:.0} MiB/s |",
            m.name,
            m.compressed as f64 / (1024.0 * 1024.0),
            m.ratio(fixed.len()),
            m.compress_mib_s,
            m.decompress_mib_s,
        );
    }

    // --- formats ------------------------------------------------------------
    let dir = std::env::temp_dir().join("bizstd-bench");
    let _ignored = std::fs::create_dir_all(&dir);

    let _ = writeln!(out, "\n## Formats, the same records stored six ways\n");
    let _ = writeln!(
        out,
        "**append** means records can be added to a finished file without rewriting it, and the \
         file stays readable while that happens. **slice** means one part can be read without \
         decoding everything before it.\n"
    );
    let _ = writeln!(out, "| format | size | vs jsonl | write | read | append | slice |");
    let _ = writeln!(out, "|---|---:|---:|---:|---:|:---:|:---:|");
    let formats = formats::run_all(&samples, &dir);
    let baseline = formats.first().map_or(1, |m| m.bytes.max(1));
    for m in &formats {
        let _ = writeln!(
            out,
            "| {} | {:.1} MiB | {:.2}x | {:.2} s | {:.2} s | {} | {} |",
            m.name,
            m.bytes as f64 / (1024.0 * 1024.0),
            baseline as f64 / m.bytes.max(1) as f64,
            m.write_seconds,
            m.read_seconds,
            if m.appendable { "yes" } else { "no" },
            if m.sliceable { "yes" } else { "no" },
        );
    }

    let _ = writeln!(out, "\n## Environment\n");
    let _ = writeln!(out, "- os: `{}`", std::env::consts::OS);
    let _ = writeln!(out, "- arch: `{}`", std::env::consts::ARCH);
    let _ = writeln!(
        out,
        "- parallelism reported: {}",
        std::thread::available_parallelism().map_or(0, std::num::NonZero::get)
    );
    let _ = writeln!(
        out,
        "\nEverything here is single-threaded on purpose: the container compresses one frame at a \
         time on the thread that is writing, so a parallel number would describe a program nobody \
         is running.\n"
    );

    let _ignored = std::fs::remove_dir_all(&dir);
}
